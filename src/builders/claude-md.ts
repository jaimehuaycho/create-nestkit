// ────────────────────────────────────────────────────────────────────────────
// Entry point — returns all files to generate as a map
// ────────────────────────────────────────────────────────────────────────────
export function buildAllClaudeFiles(
    manifests: Manifest[],
    dbDriver:  string,
    projectName: string,
): Map<string, string> {
    const c = ctx(manifests, dbDriver, projectName);
    const files = new Map<string, string>();

    // Root file is lean; everything else is a rule scoped by `paths:` so it only loads on demand.
    files.set('.claude/CLAUDE.md', buildClaudeMd(manifests, dbDriver, projectName));

    files.set('.claude/rules/api-patterns.md',
        withPaths(['src/modules/**', 'src/app/**'], buildApiPatternsClaudeMd(c)));
    files.set('.claude/rules/shared.md',
        withPaths(['src/shared/**'], buildSharedClaudeMd(c)));
    files.set('.claude/rules/config.md',
        withPaths(['src/config/**', '.env.example'], buildConfigClaudeMd()));

    if (c.hasDb)      files.set('.claude/rules/database.md',
        withPaths(['src/database/**', 'src/**/*.entity.ts'], buildDatabaseClaudeMd(c.dbDriver, c.hasAuth)));
    if (c.hasAuth)    files.set('.claude/rules/auth.md',
        withPaths(['src/app/auth/**', 'src/modules/users/**', 'src/modules/roles/**'], buildAuthClaudeMd()));
    if (c.hasMail || c.hasSock || c.hasPdf || c.hasObserve)
        files.set('.claude/rules/plugins.md', withPaths(['src/plugins/**'], buildPluginsClaudeMd(c)));

    // Project journal — separate from the generated rules above, meant to be written to
    // (not regenerated) as the project evolves. See buildContextReadme() for the rationale.
    files.set('.claude/context/README.md',    buildContextReadme());
    files.set('.claude/context/decisions.md', buildDecisionsSeed(projectName));
    files.set('.claude/context/plans/README.md', buildPlansReadme());

    return files;
}
