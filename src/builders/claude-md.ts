    l.push(`MY_OPT: Joi.number().default(42),`);
    l.push(`\`\`\``);

    l.push(``, `## Environment Helpers`);
    l.push(`- \`getEnvSettings(nodeEnv)\` → \`{ logger: LogLevel[], swagger: boolean }\``);
