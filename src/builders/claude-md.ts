import { Manifest } from '../generator';

// ── Types ─────────────────────────────────────────────────────────────────────
interface BuildContext {
    ids:        Set<string>;
    hasDb:      boolean;
    hasAuth:    boolean;
    hasMail:    boolean;
    hasSock:    boolean;
    hasPdf:     boolean;
    hasObserve: boolean;
    dbDriver:   string;
    name:       string;
}

function ctx(manifests: Manifest[], dbDriver: string, projectName: string): BuildContext {
    const ids = new Set(manifests.map(m => m.id));
    return {
        ids,
        hasDb:      ids.has('database'),
        hasAuth:    ids.has('auth'),
        hasMail:    ids.has('mailer'),
        hasSock:    ids.has('socket'),
        hasPdf:     ids.has('pdf'),
        hasObserve: ids.has('observe'),
        dbDriver,
        name: projectName,
    };
}

