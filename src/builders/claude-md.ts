    const l: string[] = [];

    l.push(`# database/ — TypeORM Reference`);
    l.push(``, `Driver: \`${dbDriver}\`. All config comes from env vars (see \`src/config/CLAUDE.md\`).`);

    l.push(``, `## BaseEntitySoftDelete (\`src/database/entities/base.entity.ts\`)`);
    l.push(`All entities must extend this. It provides:`);
    l.push(`\`\`\`typescript`);
    l.push(`createdAt: Date   // @CreateDateColumn`);
    l.push(`updatedAt: Date   // @UpdateDateColumn`);
    l.push(`deletedAt: Date   // @DeleteDateColumn — set by softDelete(), null for active records`);
    l.push(`\`\`\``);
    l.push(`TypeORM automatically excludes soft-deleted rows from all \`find*()\` queries.`);
    l.push(`Use \`{ withDeleted: true }\` to include them.`);

    l.push(``, `## Entity Conventions`);
    l.push(`\`\`\`typescript`);
    l.push(`@Entity('products')   // table name: snake_case plural`);
