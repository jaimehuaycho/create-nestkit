// .claude/rules/plugins.md — port/adapter pattern and plugin APIs
// ────────────────────────────────────────────────────────────────────────────
export function buildPluginsClaudeMd(c: ReturnType<typeof ctx>): string {
    const l: string[] = [];

    l.push(`# plugins/ — Port & Adapter Reference`);
    l.push(``, `Plugins follow the Port & Adapter pattern — consumers inject the port (abstract class), never the concrete adapter.`);
    l.push(`Swapping implementations (e.g., SMTP → Resend) requires zero changes to business code.`);

    l.push(``, `## Plugin Structure`);
    l.push(`\`\`\``);
    l.push(`plugins/{name}/`);
    l.push(`├── {name}.port.ts           # abstract class — the contract`);
    l.push(`├── {name}.module.ts         # @Global() DynamicModule.register()`);
    l.push(`├── exceptions/              # plugin-specific exception classes`);
    l.push(`└── {adapter}/`);
    l.push(`    ├── {adapter}.adapter.ts # extends port`);
    l.push(`    ├── {adapter}.config.ts  # reads env vars via ConfigService`);
    l.push(`    └── {adapter}.module.ts  # provides adapter, exports port`);
    l.push(`\`\`\``);
    l.push(`Module.register() re-exports the adapter module — this makes the port globally injectable.`);

    if (c.hasMail) {
        l.push(``, `## Mailer Plugin`);
        l.push(`\`\`\`typescript`);
        l.push(`import { MailerPort, MailOptions } from 'src/plugins/mailer/mailer.port';`);
        l.push(``);
        l.push(`constructor(private readonly mailer: MailerPort) {}`);
        l.push(``);
        l.push(`// Fire-and-forget (errors are logged, not thrown)`);
        l.push(`this.mailer.send({`);
        l.push(`    to:      'user@example.com',`);
        l.push(`    subject: 'Welcome',`);
        l.push(`    html:    '<p>Hello!</p>',`);
        l.push(`    // text, template, context, attachments also available`);
        l.push(`});`);
        l.push(`\`\`\``);
        l.push(`Transport selected at startup via \`MAILER_TRANSPORT=smtp|api\` env var.`);
        l.push(`- SMTP: uses \`@nestjs-modules/mailer\` with Handlebars for templates.`);
        l.push(`- API: compatible with Resend by default — override \`buildPayload()\` for other providers.`);
    }

    if (c.hasSock) {
        l.push(``, `## Socket Plugin`);
        l.push(`\`\`\`typescript`);
        l.push(`import { SocketService } from 'src/plugins/socket/socket.service';`);
        l.push(``);
        l.push(`constructor(private readonly socket: SocketService) {}`);
        l.push(``);
        l.push(`this.socket.emit('user.created', { id: user.id });`);
        l.push(`// Namespace: WEBSOCKET_NAMESPACE env var (default: 'app')`);
        l.push(`\`\`\``);
    }

    if (c.hasPdf) {
        l.push(``, `## PDF Plugin`);
        l.push(`\`\`\`typescript`);
        l.push(`import { PdfPort, PdfOptions } from 'src/plugins/pdf/pdf.port';`);
        l.push(``);
        l.push(`constructor(private readonly pdf: PdfPort) {}`);
        l.push(``);
        l.push(`const buffer = await this.pdf.generate('<html>...</html>', {`);
        l.push(`    format: 'Letter',          // default`);
        l.push(`    printBackground: true,     // default`);
        l.push(`    margin: { top: '10mm' },`);
        l.push(`});`);
        l.push(`// Returns Buffer — stream to client or save to storage`);
        l.push(`\`\`\``);
        l.push(`Throws \`PdfGenerationException\` (500) on Puppeteer errors.`);
        l.push(`Puppeteer browser is launched once at module init and reused.`);
    }

    if (c.hasObserve) {
        l.push(``, `## Observability Plugin`);
        l.push(`No port/adapter — \`@nestjs/observe\` has one implementation, nothing to swap. Structure:`);
        l.push(`\`\`\``);
        l.push(`plugins/observe/`);
        l.push(`├── observe.instrument.ts  # createObserveModule() call site — the ONLY one allowed`);
        l.push(`├── observe.config.ts      # ObserveConfig — reads OBSERVE_* via ConfigService`);
        l.push(`└── observe.module.ts      # ObservabilityModule — forRootAsync(ObserveConfig)`);
        l.push(`\`\`\``);
        l.push(`\`app.module.ts\` only ever imports \`ObservabilityModule\` — same \`forRootAsync\` +`);
        l.push(`\`ConfigService\` pattern as \`database.module.ts\`, never a raw env var.`);
        l.push(``);
        l.push(`\`main.ts\` imports \`ObserveInstrument\` straight from \`observe.instrument.ts\` instead —`);
        l.push(`\`NestFactory.create(AppModule, { instrument: ObserveInstrument })\` needs it *before* Nest's`);
        l.push(`DI container exists, so it can't come from a provider. \`observe.instrument.ts\` must stay`);
        l.push(`the single call site for \`createObserveModule()\`: calling it twice creates two independent`);
        l.push(`instrument/module pairs that don't share state.`);
        l.push(``);
        l.push(`Credentials (\`OBSERVE_APP_KEY\` / \`OBSERVE_APP_SECRET\`) — sign up at`);
        l.push(`[observe.nestjs.com](https://observe.nestjs.com). Missing or invalid ones don't crash the`);
        l.push(`app — the collector answers 401 and the batch is dropped, silently.`);
    }

    l.push(``, `## Adding a New Plugin`);
    l.push(`Use the \`/nest-plugin <Name> <Adapter>\` skill — it scaffolds the full port/adapter structure.`);
    l.push(`Key requirements:`);
    l.push(`- Port must be an \`abstract class\` (not interface) so NestJS DI can use it as a token.`);
    l.push(`- \`{Name}Module.register()\` returns \`{ module, imports: [adapterModule], exports: [adapterModule] }\`.`);
    l.push(`- Add env vars to \`.env.example\` and \`src/config/env.validation.ts\`.`);
    l.push(`- All errors → exception classes in \`exceptions/\`, never inline throws.`);

    return l.join('\n') + '\n';
}

