    l.push(``, `## Pagination`);
    l.push(`Generic — usable for any list endpoint, DB-backed or not.`);
    l.push(`\`\`\`typescript`);
    l.push(`// Params DTO`);
    l.push(`export class FindAllProductsParamsDto extends PaginationParamsDto { ... }`);
    l.push(`// PaginationParamsDto has: page (default 1), limit (default 10)`);
