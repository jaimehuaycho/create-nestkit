import { Manifest } from '../generator';
import { PasswordHasher, PasswordHasherId, getPasswordHasher } from './password-hasher';

// ── Types ─────────────────────────────────────────────────────────────────────
interface BuildContext {
    ids:        Set<string>;
    hasDb:      boolean;
    hasAuth:    boolean;
    hasMail:    boolean;
    hasSock:    boolean;
    hasPdf:     boolean;
    hasObserve: boolean;
    dbDriver:   string;
    name:       string;
    hasher:     PasswordHasher;   // only meaningful with Auth; defaults to bcrypt
}

function ctx(manifests: Manifest[], dbDriver: string, projectName: string, passwordHasher?: PasswordHasherId): BuildContext {
    const ids = new Set(manifests.map(m => m.id));
    return {
        ids,
        hasDb:      ids.has('database'),
        hasAuth:    ids.has('auth'),
        hasMail:    ids.has('mailer'),
        hasSock:    ids.has('socket'),
        hasPdf:     ids.has('pdf'),
        hasObserve: ids.has('observe'),
        dbDriver,
        name: projectName,
        hasher: getPasswordHasher(passwordHasher),
    };
}

// ────────────────────────────────────────────────────────────────────────────
// Root .claude/CLAUDE.md — what Claude must know every session. Kept lean on purpose:
// Claude Code loads it in full on every request, and adherence drops past ~200 lines.
// Area conventions live in .claude/rules/*.md with `paths:` so they load only when needed.
// ────────────────────────────────────────────────────────────────────────────
export function buildClaudeMd(manifests: Manifest[], dbDriver: string, projectName: string): string {
    const c = ctx(manifests, dbDriver, projectName);
    const l: string[] = [];
    const hasPlugins = c.hasMail || c.hasSock || c.hasPdf || c.hasObserve;

    l.push(`# ${c.name} — Development Guide`);
    l.push(``, `NestJS API generated by \`create-nestkit\`. Follow the conventions below and in \`.claude/rules/\``);
    l.push(`unless there is a reason not to (see "Starting Point, Not a Contract").`);

    // Verification first: giving Claude a check it can run is the biggest quality lever.
    l.push(``, `## Verify your work`);
    l.push(`Run these before saying a task is done. Fix the root cause; don't silence an error to make a check pass.`);
    l.push(`\`\`\`bash`);
    l.push(`npm run typecheck      # tsc --noEmit`);
    l.push(`npm run lint`);
    l.push(`npm test               # the scaffold ships no spec files, so it exits non-zero until you add one`);
    l.push(`npm run build`);
    l.push(`\`\`\``);
    l.push(`Add a test with each feature. Edited files are formatted automatically by a hook; don't hand-format.`);
    l.push(`Imports inside \`src/\` are relative and end in \`.js\` (\`'../shared/x/index.js'\`); never the \`src/...\` path alias, which fails typecheck in ESM.`);

    l.push(``, `## Commands`, `\`\`\`bash`);
    l.push(`npm run start:dev      # development with watch`);
    if (c.hasDb) {
        l.push(`npm run migration:generate -- src/database/migrations/<Name>   # none shipped: create yours (e.g. \`Init\`), never auto-run`);
        l.push(`npm run migration:run`);
        l.push(`npm run migration:revert`);
        l.push(c.hasAuth
            ? `npm run seed           # roles (root/admin/user) + root user, idempotent; prints a random root password once if SEED_ROOT_PASSWORD is empty`
            : `npm run seed           # empty seed script: add your seeders`);
    }
    l.push(`\`\`\``);

    l.push(``, `## Project structure`, `\`\`\``);
    l.push(`src/`);
    l.push(`├── app/        # Logic modules, no own DB table (${c.hasAuth ? 'auth, ' : ''}health)`);
    if (c.hasDb) l.push(`├── modules/    # Domain modules: one folder = one DB table`);
    if (hasPlugins)
        l.push(`├── plugins/    # ${[c.hasMail && 'mailer', c.hasSock && 'socket', c.hasPdf && 'pdf', c.hasObserve && 'observe'].filter(Boolean).join(', ')}`);
    if (c.hasDb) l.push(`├── database/   # TypeORM config, base entity, migrations, seeds`);
    l.push(`├── config/     # @Global AppConfigModule, Joi env validation`);
    l.push(`└── shared/     # ${c.hasDb ? 'DtoRepository, ' : ''}swagger utils, filters, DTOs`);
    l.push(`\`\`\``);

    // Canonical examples — only point at code that actually exists in this project.
    l.push(``, `## Read these first`);
    if (c.hasAuth) {
        l.push(`- \`src/modules/users/\`: full CRUD module (entity → DTO → service → controller → exceptions)`);
        l.push(`- \`src/app/auth/\`: JWT auth, guards, decorators`);
    } else if (c.hasDb) {
        l.push(`- No domain module yet. Run \`/nest-module <Name>\` to scaffold the first one.`);
    } else {
        l.push(`- Bare scaffold: no domain modules and no database. Conventions: \`.claude/rules/api-patterns.md\`.`);
    }

    // Where conventions live — path-scoped rules load on demand, so list them instead of importing.
    l.push(``, `## Conventions (loaded automatically when you touch these paths)`);
    l.push(`| Path | Rule file |`, `|---|---|`);
    l.push(`| \`src/modules/**\`, \`src/app/**\` | \`.claude/rules/api-patterns.md\` |`);
    l.push(`| \`src/shared/**\` | \`.claude/rules/shared.md\` |`);
    l.push(`| \`src/config/**\` | \`.claude/rules/config.md\` |`);
    if (c.hasDb)   l.push(`| \`src/database/**\`, entities | \`.claude/rules/database.md\` |`);
    if (c.hasAuth) l.push(`| \`src/app/auth/**\`, \`src/modules/users/**\` | \`.claude/rules/auth.md\` |`);
    if (hasPlugins) l.push(`| \`src/plugins/**\` | \`.claude/rules/plugins.md\` |`);
    // Path-scoped rules only load once a matching file is read or edited, so planning work before touching
    // any file would otherwise happen without them. Say so explicitly.
    l.push(``, `Rules load when you first read or edit a matching file. When you plan or review work in an area before`);
    l.push(`touching any file there, read its rule file first.`);

    l.push(``, `## Active plugins`);
    if (!c.hasDb && !c.hasAuth && !hasPlugins) {
        l.push(`- None: core only (config, health check, Swagger, global exception filter).`);
    } else {
        if (c.hasDb)      l.push(`- **Database** (${c.dbDriver}): TypeORM, migrations, seeds`);
        if (c.hasAuth)    l.push(`- **Auth**: JWT, refresh rotation, roles`);
        if (c.hasMail)    l.push(`- **Mailer**: Nest's mail module (\`@nestjs/mail\`); transport chosen with \`MAIL_TRANSPORT\``);
        if (c.hasSock)    l.push(`- **WebSockets**: Socket.io`);
        if (c.hasPdf)     l.push(`- **PDF**: Puppeteer`);
        if (c.hasObserve) l.push(`- **Observability**: Nest Observe (needs credentials from observe.nestjs.com)`);
    }

    l.push(``, `## Tooling in \`.claude/\``);
    l.push(`- **Skills** (user-invoked): ${[c.hasDb && '`/nest-module <Name>`', '`/nest-exception <Module> <Type>`', '`/nest-plugin <Name> <Adapter>`', c.hasDb && '`/db-map`'].filter(Boolean).join(', ')}`);
    l.push(`- **Subagents**: \`code-reviewer\` (read-only review of the diff against these rules), \`test-runner\` (runs checks, reports failures only)`);
    l.push(`- **Hooks** (\`settings.json\`): format edited files; block edits to \`.env*\`, lockfiles${c.hasDb ? ', applied migrations' : ''} and \`.git/\``);
    l.push(`- **Permissions**: \`.env\` files can't be read; ${c.hasDb ? 'migrations, seed, ' : ''}\`git push\` ask first. Personal overrides go in \`.claude/settings.local.json\` (gitignored).`);

    // Flexible-base philosophy — explicit so Claude Code (or a human) doesn't treat the
    // generated rules as immutable. Deviations are fine; silent, unrecorded drift isn't.
    l.push(``, `## Starting Point, Not a Contract`);
    l.push(`\`create-nestkit\` generated this structure once and does not keep it in sync. Deviating from`);
    l.push(`\`.claude/rules/*.md\` is fine; deviating silently is not:`);
    l.push(`1. Log it in \`.claude/context/decisions.md\`: what changed and why. Append, don't rewrite.`);
    l.push(`2. If it is a lasting convention, update the matching rule file too. A rule that lies is worse than none.`);
    l.push(`Save non-trivial plans in \`.claude/context/plans/\` before executing them.`);

    return l.join('\n') + '\n';
}

// ────────────────────────────────────────────────────────────────────────────
// .claude/rules/api-patterns.md — module, service, controller and exception conventions.
// ────────────────────────────────────────────────────────────────────────────
export function buildApiPatternsClaudeMd(c: ReturnType<typeof ctx>): string {
    const l: string[] = [];

    l.push(`# API patterns — modules, controllers, exceptions`);
    l.push(``);
    l.push(`## Imports`);
    l.push(`Imports inside \`src/\` are **relative and end in \`.js\`** (NodeNext module resolution), e.g.`);
    l.push(`\`import { X } from '../../../shared/utils/swagger/index.js'\` from \`src/modules/<name>/controllers/\`. Barrels are`);
    l.push(`\`index.js\`. Do not use the \`src/...\` path alias: it fails typecheck in ESM projects. Snippets below assume a file`);
    l.push(`three folders deep (\`src/modules/<name>/<layer>/\`); adjust the \`../\` count for your file.`);
    l.push(``);

    if (c.hasDb) {
        // Module anatomy
        l.push(``, `## Module Anatomy — \`modules/{name}s/\``);
        l.push(`\`\`\``);
        l.push(`├── entities/{name}.entity.ts       # extends BaseEntitySoftDelete`);
        l.push(`├── dto/{name}.dto.ts               # @DtoField / @DtoRelation`);
        l.push(`├── dto/create-{name}.dto.ts`);
        l.push(`├── dto/update-{name}.dto.ts`);
        l.push(`├── dto/find-all-{name}s-params.dto.ts    # extends PaginationParamsDto`);
        l.push(`├── dto/find-all-{name}s-response.dto.ts  # extends PaginationResponseDto<Dto>`);
        l.push(`├── services/{name}s.service.ts`);
        l.push(`├── controllers/{name}s.controller.ts`);
        l.push(`├── exceptions/{name}-not-found.exception.ts`);
        l.push(`├── exceptions/{name}-already-exists.exception.ts`);
        l.push(`├── exceptions/index.ts`);
        l.push(`└── {name}s.module.ts`);
        l.push(`\`\`\``);

        // Service pattern
        l.push(``, `## Service Pattern — CRITICAL`);
        l.push(c.hasAuth
            ? `Full reference: \`src/modules/users/services/users.service.ts\``
            : `Follow this pattern for every service you add (no existing module to point at yet):`);
        l.push(``);
        l.push(`\`\`\`typescript`);
        l.push(`// DTO class is ALWAYS the first argument`);
        l.push(`findAll<T>(dto, params)                          // → PaginationResponseDto<T>`);
        l.push(`findOne<T>(dto, where, { throwException: false}) // → T | null`);
        l.push(`findOne<T>(dto, where, options?)                 // → T  (throws if missing)`);
        l.push(`findOneById<T>(dto, id, options?)`);
        l.push(`// Add findOneBy<Field> only when that field exists on this entity`);
        l.push(``);
        l.push(`create<T>(returnDto, createDto, options?)        // → T`);
        l.push(`update<T>(returnDto, id, updateDto, options?)    // → T`);
        l.push(`remove(id, options?)                             // void`);
        l.push(`\`\`\``);
        l.push(`- Existence check → \`rawRepo.existsBy(where)\` (SELECT 1, no DTO overhead)`);
        l.push(`- Create → \`repo.create()\` + explicit field assignment (no spread)`);
        l.push(`- Return → \`new DtoRepository(repo).findOne({ dto: returnDto, where: { id } })\` (transaction-safe)`);
        l.push(`- All in \`.claude/rules/shared.md\` → DtoRepository, MutationOptions, FindOptions, pagination`);
    }

    // Controller pattern — general Nest/Swagger convention, applies even without a database
    // (webhook receivers, PDF endpoints, etc. still need consistent Swagger + error handling).
    l.push(``, `## Controller Pattern — CRITICAL`);
    if (c.hasAuth) l.push(`Full reference: \`src/modules/users/controllers/users.controller.ts\``, ``);
    l.push(`\`\`\`typescript`);
    l.push(`import { ApiNotFound, ApiUnauthorized, ApiConflict } from '../../../shared/utils/swagger/index.js';`);
    if (c.hasAuth) l.push(`import { AdminUp, RootOnly, UserUp } from '../../../app/auth/decorators/index.js';`);
    l.push(`/**`);
    l.push(` * Error dictionary: X_NOT_FOUND 404, X_ALREADY_EXISTS 409`);
    if (c.hasAuth) l.push(` *   INVALID_TOKEN 401, INSUFFICIENT_PERMISSIONS 403`);
    l.push(` */`);
    l.push(`@ApiTags('...') @ApiBearerAuth('access-token') @Controller('...')`);
    l.push(`export class XController {`);
    l.push(`    @Get(':id')${c.hasAuth ? ' @AdminUp()' : ''}`);
    l.push(`    @ApiOperation({ summary: '...', description: '...' })`);
    l.push(`    @ApiOkResponse({ type: XDto })`);
    l.push(`    @ApiNotFound({ code: 'X_NOT_FOUND', message: 'X not found.' })`);
    l.push(`    @ApiUnauthorized({ code: 'INVALID_TOKEN', message: 'Invalid or expired token.' })`);
    l.push(`    async findOne(@Param('id', ParseIntPipe) id: number): Promise<XDto> {`);
    l.push(`        return await this.service.findOneById(XDto, id);`);
    l.push(`    }`);
    l.push(`}`);
    l.push(`\`\`\``);
    l.push(`- \`async\` + \`return await\` on every method`);
    l.push(`- Error decorators are variadic: \`@ApiNotFound(err1, err2)\` shows dropdown in Swagger for multiple codes`);
    l.push(`- \`'access-token'\` = security scheme name from \`src/config/helpers/swagger.ts\``);
    l.push(`- Full swagger util reference → \`.claude/rules/shared.md\``);

    // Exception pattern
    l.push(``, `## Exception Pattern`);
    l.push(`All exceptions → \`{ statusCode, error, message, path, timestamp }\` via HttpExceptionFilter.`);
    l.push(`The \`error\` field (SCREAMING_SNAKE_CASE) is what the frontend uses to distinguish same-status errors.`, ``);
    l.push(`\`\`\`typescript`);
    l.push(`export class XNotFoundException extends NotFoundException {`);
    l.push(`    constructor() { super({ message: 'X not found.', error: 'X_NOT_FOUND' }); }`);
    l.push(`}`);
    l.push(`\`\`\``);
    l.push(`- One class per exception, one file per class, barrel in \`exceptions/index.ts\``);
    l.push(`- **Never** throw NestJS built-ins inline in services — always use the exception class`);

    return l.join('\n') + '\n';
}

// Prepends `paths:` frontmatter so Claude Code loads a rule only when it reads or edits a
// matching file (rules without `paths` load into every session, like CLAUDE.md itself).
export function withPaths(paths: string[], body: string): string {
    return `---\npaths:\n${paths.map(p => `  - "${p}"`).join('\n')}\n---\n\n${body}`;
}


