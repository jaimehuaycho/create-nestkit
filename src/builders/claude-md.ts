    l.push(``, `## Migrations`);
    l.push(`\`\`\`bash`);
    l.push(`# Generate — compares entities vs DB schema:`);
    l.push(`npm run migration:generate -- src/database/migrations/<DescriptiveName>`);
    l.push(`# Run all pending:`);
    l.push(`npm run migration:run`);
    l.push(`# Revert last:`);
    l.push(`npm run migration:revert`);
    l.push(`\`\`\``);
    l.push(`Config: \`src/database/config/data-source.ts\`.`);
    l.push(`Never use \`synchronize: true\` in any environment — always use migrations.`);

    l.push(``, `## Transactions via MutationOptions`);
    l.push(`\`\`\`typescript`);
    l.push(`// In a higher-level service that coordinates two modules:`);
    l.push(`await dataSource.transaction(async (manager) => {`);
    l.push(`    await usersService.create(UserDto, dto, { manager });`);
    l.push(`    await ordersService.create(OrderDto, orderDto, { manager });`);
    l.push(`});`);
    l.push(`// Both mutations share the same transaction — if one fails, both roll back.`);
