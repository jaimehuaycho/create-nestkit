// ────────────────────────────────────────────────────────────────────────────
// .claude/rules/database.md — TypeORM, migrations, base entity
// ────────────────────────────────────────────────────────────────────────────
export function buildDatabaseClaudeMd(dbDriver: string, hasAuth: boolean): string {
    const l: string[] = [];

    l.push(`# database/ — TypeORM Reference`);
    l.push(``, `Driver: \`${dbDriver}\`. All config comes from env vars (see \`.claude/rules/config.md\`).`);

    l.push(``, `## BaseEntitySoftDelete (\`src/database/entities/base.entity.ts\`)`);
    l.push(`All entities must extend this. It provides:`);
    l.push(`\`\`\`typescript`);
    l.push(`createdAt: Date   // @CreateDateColumn`);
    l.push(`updatedAt: Date   // @UpdateDateColumn`);
    l.push(`deletedAt: Date   // @DeleteDateColumn — set by softDelete(), null for active records`);
    l.push(`\`\`\``);
    l.push(`TypeORM automatically excludes soft-deleted rows from all \`find*()\` queries.`);
    l.push(`Use \`{ withDeleted: true }\` to include them.`);

    l.push(``, `## Entity Conventions`);
    l.push(`\`\`\`typescript`);
    l.push(`@Entity('products')   // table name: snake_case plural`);
    l.push(`export class Product extends BaseEntitySoftDelete {`);
    l.push(`    @PrimaryGeneratedColumn({ name: 'product_id' }) id: number;   // always {entity}_id in DB`);
    l.push(`    @Column({ name: 'name', type: 'varchar', length: 150 }) name: string;`);
    l.push(`    @Column({ name: 'category_id', type: 'int' }) categoryId: number;`);
    l.push(`    @ManyToOne(() => Category, cat => cat.products)`);
    l.push(`    @JoinColumn({ name: 'category_id' })             // FK column must have @JoinColumn`);
    l.push(`    category: Category;`);
    l.push(`}`);
    l.push(`\`\`\``);

    l.push(``, `## Migrations`);
    l.push(`\`\`\`bash`);
    l.push(`# Generate — compares entities vs DB schema:`);
    l.push(`npm run migration:generate -- src/database/migrations/<DescriptiveName>`);
    l.push(`# Run all pending:`);
    l.push(`npm run migration:run`);
    l.push(`# Revert last:`);
    l.push(`npm run migration:revert`);
    l.push(`\`\`\``);
    l.push(`Config: \`src/database/config/data-source.ts\`.`);
    l.push(`Never use \`synchronize: true\` in any environment — always use migrations.`);

    l.push(``, `## Transactions via MutationOptions`);
    l.push(`\`\`\`typescript`);
    l.push(`// In a higher-level service that coordinates two modules:`);
    l.push(`await dataSource.transaction(async (manager) => {`);
    l.push(`    await usersService.create(UserDto, dto, { manager });`);
    l.push(`    await ordersService.create(OrderDto, orderDto, { manager });`);
    l.push(`});`);
    l.push(`// Both mutations share the same transaction — if one fails, both roll back.`);
    l.push(`// DtoRepository(repo) in each service uses the manager-bound repo automatically.`);
    l.push(`\`\`\``);

    l.push(``, `## Seed (\`src/database/seeds/seed.ts\`)`);
    if (hasAuth) {
        l.push(`Run standalone via \`npm run seed\`. Idempotent: creates the root/admin/user roles (ids 1/2/3) and the root user`);
        l.push(`if they don't exist yet. Controlled by env vars: \`SEED_ROOT_EMAIL\`, \`SEED_ROOT_PASSWORD\`.`);
        l.push(`Adapt the seed if the users table has different fields.`);
    } else {
        l.push(`Run standalone via \`npm run seed\`. The script only opens the connection and has no seeders yet:`);
        l.push(`add yours between the connect and destroy calls, and keep them idempotent.`);
    }

    return l.join('\n') + '\n';
}

