// ────────────────────────────────────────────────────────────────────────────
// Entry point — returns all files to generate as a map
// ────────────────────────────────────────────────────────────────────────────
export function buildAllClaudeFiles(
    manifests: Manifest[],
    dbDriver:  string,
    projectName: string,
): Map<string, string> {
    const c = ctx(manifests, dbDriver, projectName);
    const files = new Map<string, string>();

    // Root navigator — imports all rules files
    files.set('.claude/CLAUDE.md', buildClaudeMd(manifests, dbDriver, projectName));

    // All detailed rules live under .claude/rules/ — unified, nothing scattered in src/
    files.set('.claude/rules/shared.md',   buildSharedClaudeMd(c));
    files.set('.claude/rules/config.md',   buildConfigClaudeMd(c.hasObserve));

    if (c.hasDb)   files.set('.claude/rules/database.md', buildDatabaseClaudeMd(c.dbDriver));
    if (c.hasAuth) files.set('.claude/rules/auth.md',     buildAuthClaudeMd());
    if (c.hasMail || c.hasSock || c.hasPdf)
        files.set('.claude/rules/plugins.md', buildPluginsClaudeMd(c));

    // Project journal — separate from the generated rules above, meant to be written to
    // (not regenerated) as the project evolves. See buildContextReadme() for the rationale.
    files.set('.claude/context/README.md',    buildContextReadme());
    files.set('.claude/context/decisions.md', buildDecisionsSeed(projectName));
    files.set('.claude/context/plans/README.md', buildPlansReadme());

    return files;
}
