// .claude/rules/shared.md — all shared utilities
// ────────────────────────────────────────────────────────────────────────────
export function buildSharedClaudeMd(c: ReturnType<typeof ctx>): string {
    const l: string[] = [];

    l.push(`# shared/ — Utilities Reference`);
    l.push(``, `Everything in \`src/shared/\` is usable from any module. Nothing here imports from \`modules/\` or \`app/\`.`);

    if (c.hasDb) {
        l.push(``, `## DtoRepository (\`src/shared/orm\`)`);
        l.push(`Wraps TypeORM \`Repository<E>\` with automatic SELECT + JOIN derived from the DTO class.`);
        l.push(`\`\`\`typescript`);
        l.push(`private readonly repo: DtoRepository<User>;`);
        l.push(`constructor(@InjectRepository(User) private readonly rawRepo: Repository<User>) {`);
        l.push(`    this.repo = new DtoRepository(rawRepo);`);
        l.push(`}`);
        l.push(`// Usage`);
        l.push(`const result = await this.repo.findOne({ dto: UserDto, where: { id } });`);
        l.push(`const page   = await this.repo.findPaginated({ dto: UserDto, pagination: params, where: {}, order: {} });`);
        l.push(`// In mutations — builds from the same repo for transaction safety:`);
        l.push(`const saved = await repo.save(entity);`);
        l.push(`return (await new DtoRepository(repo).findOne({ dto: returnDto, where: { id: saved.id } }))!;`);
        l.push(`\`\`\``);

        l.push(``, `## @DtoField and @DtoRelation`);
        l.push(`Decorators that drive both TypeORM SELECT and class-transformer serialization.`);
        l.push(`\`\`\`typescript`);
        l.push(`import { DtoField, DtoRelation } from '../../../shared/orm/index.js';`);
        l.push(``);
        l.push(`export class ProductDto {`);
        l.push(`    @DtoField() id!: number;           // scalar → SELECT product_id`);
        l.push(`    @DtoField() name!: string;          // scalar → SELECT name`);
        l.push(`    @DtoField() createdAt!: Date;`);
        l.push(`    @DtoRelation(() => CategoryDto)     // relation → LEFT JOIN categories`);
        l.push(`    category!: CategoryDto;`);
        l.push(`}`);
        l.push(`\`\`\``);
        l.push(`Only \`@DtoField\` / \`@DtoRelation\` fields are included in SELECT — adding a field to the DTO automatically includes it in all queries.`);

        l.push(``, `## FindOptions and MutationOptions`);
        l.push(`\`\`\`typescript`);
        l.push(`import { FindOptions, MutationOptions } from '../../../shared/dto/index.js';`);
        l.push(``);
        l.push(`// FindOptions`);
        l.push(`{ throwException?: boolean }  // false = return null instead of throwing NotFoundException`);
        l.push(``);
        l.push(`// MutationOptions`);
        l.push(`{ manager?: EntityManager, hardDelete?: boolean }`);
        l.push(`// manager  = pass an EntityManager to run inside an existing transaction`);
        l.push(`// hardDelete = true → repo.delete(), false (default) → repo.softDelete()`);
        l.push(`\`\`\``);
    }

    l.push(``, `## Pagination`);
    l.push(`Generic — usable for any list endpoint, DB-backed or not.`);
    l.push(`\`\`\`typescript`);
    l.push(`// Params DTO`);
    l.push(`export class FindAllProductsParamsDto extends PaginationParamsDto { ... }`);
    l.push(`// PaginationParamsDto has: page (default 1), limit (default 10)`);
    l.push(``);
    l.push(`// Response DTO`);
    l.push(`export class FindAllProductsResponseDto extends PaginationResponseDto<ProductDto> {`);
    l.push(`    @ApiProperty({ type: [ProductDto] }) declare data: ProductDto[];`);
    l.push(`}`);
    l.push(`// PaginationResponseDto has: data[], meta: { page, limit, total, pages }`);
    l.push(`\`\`\``);

    l.push(``, `## Swagger Response Decorators (\`src/shared/utils/swagger\`)`);
    l.push(`All decorators are **variadic** — pass one or many \`{ code, message }\` objects.`);
    l.push(`Multiple errors for the same status produce a dropdown in Swagger UI.`);
    l.push(`\`\`\`typescript`);
    l.push(`import { ApiNotFound, ApiConflict, ApiUnauthorized, ApiForbidden,`);
    l.push(`         ApiValidationError, ApiUnprocessableEntity } from '../../../shared/utils/swagger/index.js';`);
    l.push(``);
    l.push(`@ApiNotFound({ code: 'PRODUCT_NOT_FOUND', message: 'Product not found.' })`);
    l.push(`@ApiConflict({ code: 'PRODUCT_ALREADY_EXISTS', message: 'A product with this name already exists.' })`);
    l.push(`@ApiUnauthorized({ code: 'INVALID_TOKEN', message: 'Invalid or expired token.' })`);
    l.push(`@ApiForbidden({ code: 'INSUFFICIENT_PERMISSIONS', message: 'You do not have permission.' })`);
    l.push(`@ApiValidationError()  // 400 — class-validator format (always no-args)`);
    l.push(``);
    l.push(`// Multiple codes for same status:`);
    l.push(`@ApiUnauthorized(`);
    l.push(`    { code: 'INVALID_TOKEN',       message: 'Invalid or expired token.' },`);
    l.push(`    { code: 'INVALID_CREDENTIALS', message: 'Invalid credentials.' },`);
    l.push(`)`);
    l.push(`\`\`\``);
    l.push(`Response body shape (all non-400): \`{ statusCode, error, message, path, timestamp }\``);

    l.push(``, `## HttpExceptionFilter`);
    l.push(`Global filter in \`src/shared/filters/http-exception.filter.ts\`.`);
    l.push(`Normalizes ALL HttpExceptions to: \`{ statusCode, error, message, path, timestamp }\`.`);
    l.push(`- When you pass \`{ message, error }\` to an exception constructor → \`error\` is your domain code.`);
    l.push(`- When you pass a plain string → \`error\` falls back to the HTTP status code label (e.g., \`NOT_FOUND\`).`);
    l.push(`- 500s are logged with stack trace; lower statuses are not.`);

    if (c.hasAuth) {
        l.push(``, `## @CurrentUser Decorator`);
        l.push(`\`\`\`typescript`);
        l.push(`import { CurrentUser } from '../../../shared/decorators/index.js';`);
        l.push(`import type { AuthUser } from '../../../app/auth/strategies/jwt.strategy.js';`);
        l.push(``);
        l.push(`// In a controller method:`);
        l.push(`async logout(@CurrentUser() user: AuthUser): Promise<void>`);
        l.push(`async getProfile(@CurrentUser('id') id: number): Promise<UserDto>`);
        l.push(`// AuthUser = { id, roles, emailVerified, twoFactor } — what JwtStrategy puts in req.user (no e-mail: it goes stale inside a token)`);
        l.push(`\`\`\``);
    }

    l.push(``, `## Other Shared Utilities`);
    if (c.hasAuth) l.push(`- \`src/shared/security/password.util.ts\` → \`hashPassword(plain)\`, \`comparePassword(plain, hash)\`, \`needsRehash(hash)\`, \`PASSWORD_MIN_LENGTH\` (12), \`PASSWORD_MAX_BYTES\` (${c.hasher.label}, max ${c.hasher.maxBytes} bytes)`);
    l.push(`- \`src/shared/utils/code-generator.util.ts\` → \`generateCode(length)\` random alphanumeric`);
    l.push(`- \`src/shared/utils/transformers.util.ts\` → \`transformToBoolean(value, name)\` for query params`);
    l.push(`- \`src/shared/dto/error-response.dto.ts\` → Swagger schema for error responses`);
    l.push(`- \`src/shared/enums/environment.enum.ts\` → \`EnvironmentEnum\` (development, production, test, debug)`);

    return l.join('\n') + '\n';
}

